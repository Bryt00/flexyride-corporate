    settlement_bank = models.CharField(
        max_length=100, blank=True, null=True,
        help_text="Paystack bank code or MoMo network code (e.g. 040100 for GCB, MTN, VOD, ATL)."
    )
    settlement_bank_name = models.CharField(
        max_length=255, blank=True, default='',
        help_text="Human readable bank / MoMo network name."
    )
    account_number = models.CharField(
        max_length=50, blank=True, null=True,
        help_text="Bank account number or MoMo number for payouts."
    )
    account_name = models.CharField(
        max_length=255, blank=True, default='',
        help_text="Account holder name as verified by Paystack."
    )
    percentage_charge = models.DecimalField(
        max_digits=5, decimal_places=2, default=0,
        help_text="Default % of each transaction FlexyRide keeps. 0 = margin is set per-transaction at checkout."
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    objects = models.Manager()

    # Fields that, when changed, must be pushed to the Paystack subaccount.
    SUBACCOUNT_SOURCE_FIELDS = (
        'company_name', 'settlement_bank', 'account_number',
        'email', 'contact_person', 'phone', 'percentage_charge',
    )
    # Fields written by the sync itself (saving only these must not re-trigger a sync).
    SUBACCOUNT_RESULT_FIELDS = {
        'paystack_subaccount_code', 'paystack_subaccount_status',
        'paystack_subaccount_synced_at', 'account_name', 'settlement_bank_name',
    }

    class Meta:
        verbose_name_plural = "Provider Companies"

    if TYPE_CHECKING:
        from fleet.models import Vehicle, Driver
        from quotations.models import ProviderQuote, ProviderQuoteRequest
        from compliance.models import ComplianceDocument
        from sla.models import SLAMetric
        id: int
        pk: int
        quotes: models.Manager[ProviderQuote]
        quote_requests: models.Manager[ProviderQuoteRequest]
        vehicles: models.Manager[Vehicle]
        drivers: models.Manager[Driver]
        compliance_documents: models.Manager[ComplianceDocument]
        sla_metrics: models.Manager[SLAMetric]
        def get_status_display(self) -> str: ...
        def get_payout_channel_display(self) -> str: ...

    def __str__(self):
        return f"{self.company_name} [{self.get_status_display()}]"

    @property
    def has_payout_details(self) -> bool:
        return bool(self.settlement_bank and self.account_number)

    @property
    def masked_account_number(self) -> str:
        acct = self.account_number or ''
        return f"•••• {acct[-4:]}" if len(acct) > 4 else acct

    def save(self, *args, **kwargs):
        update_fields = kwargs.get('update_fields')
        previous = None
        if self.pk:
            previous = (
                ProviderCompany.objects.filter(pk=self.pk)
                .values(*self.SUBACCOUNT_SOURCE_FIELDS)
                .first()
            )

        super().save(*args, **kwargs)

        # Saves that only persist sync results must not trigger another sync (prevents recursion).
        if update_fields is not None and set(update_fields) <= self.SUBACCOUNT_RESULT_FIELDS:
            return
        if self.status != self.Status.APPROVED or not self.has_payout_details:
            return

        if not self.paystack_subaccount_code:
            # Auto-create Paystack subaccount once approved with banking details
            self.sync_paystack_subaccount()
        elif previous and any(
            self._normalize(previous[f]) != self._normalize(getattr(self, f)) for f in self.SUBACCOUNT_SOURCE_FIELDS
        ):
            self.sync_paystack_subaccount()

    @staticmethod
    def _normalize(value) -> str:
        from decimal import Decimal, InvalidOperation
        if isinstance(value, (Decimal, int, float)):
            try:
                return str(Decimal(str(value)).normalize())
            except InvalidOperation:
                return str(value)
        return str(value or '').strip()

    def sync_paystack_subaccount(self) -> dict:
        """Creates or updates this provider's Paystack subaccount and records the outcome."""
        from django.utils import timezone
        from payments import paystack

        if not self.has_payout_details:
            return {"success": False, "message": "Settlement bank and account number are required."}

        kwargs = dict(
            business_name=self.company_name,
            settlement_bank=self.settlement_bank or '',
            account_number=self.account_number or '',
            primary_contact_email=self.email,
            primary_contact_name=self.contact_person,
            primary_contact_phone=self.phone,
            description=f"FlexyRide Corporate payout account for {self.company_name}",
        )
        # Passed separately: the kwargs dict is inferred as dict[str, str], which would mistype this Decimal.
        pct = self.percentage_charge
        if self.paystack_subaccount_code:
            res = paystack.update_subaccount(
                subaccount_code=self.paystack_subaccount_code, percentage_charge=pct, **kwargs
            )
        else:
            res = paystack.create_subaccount(percentage_charge=pct, **kwargs)

        update = ['paystack_subaccount_status', 'paystack_subaccount_synced_at']
        if res.get('success'):
            code = res.get('subaccount_code')
            if code:
                self.paystack_subaccount_code = code
                update.append('paystack_subaccount_code')
            if res.get('account_name'):
                self.account_name = res['account_name']
                update.append('account_name')
            if res.get('settlement_bank_name') and self.settlement_bank_name != res['settlement_bank_name']:
                self.settlement_bank_name = res['settlement_bank_name']
                update.append('settlement_bank_name')
            self.paystack_subaccount_status = (
                "Sandbox subaccount (Paystack unreachable)" if res.get('sandbox') else "Active on Paystack"
            )
        else:
            self.paystack_subaccount_status = f"Error: {res.get('message', 'Unknown error')}"[:255]

        self.paystack_subaccount_synced_at = timezone.now()
        super().save(update_fields=update)
        self._last_subaccount_result = res
        return res
