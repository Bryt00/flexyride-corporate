from typing import TYPE_CHECKING

from django.db import models
from django.contrib.auth.models import AbstractUser, UserManager


class User(AbstractUser):
    class Role(models.TextChoices):
        CUSTOMER = 'CUSTOMER', 'Corporate Customer'
        EMPLOYEE_REQUESTER = 'EMPLOYEE_REQUESTER', 'Employee / Requester'
        BROKER = 'BROKER', 'FlexyRide Broker / Staff'
        PROVIDER_ADMIN = 'PROVIDER_ADMIN', 'Provider Administrator'
        DRIVER = 'DRIVER', 'Driver'
        SYSTEM_ADMIN = 'SYSTEM_ADMIN', 'System Administrator'

    role = models.CharField(
        max_length=30,
        choices=Role.choices,
        default=Role.CUSTOMER,
        help_text="Primary functional role of the user within FlexyRide Corporate."
    )
    phone_number = models.CharField(max_length=20, blank=True, null=True)
    is_verified = models.BooleanField(default=False)

    if TYPE_CHECKING:
        # Generated by Django at runtime; declared here for Pyright (no django-stubs mypy plugin).
        def get_role_display(self) -> str: ...

    def has_perm(self, perm, obj=None):
        if not self.is_active:
            return False
        if self.is_superuser or self.role == self.Role.SYSTEM_ADMIN:
            return True
        return super().has_perm(perm, obj)

    def has_module_perms(self, app_label):
        if not self.is_active:
            return False
        if self.is_superuser or self.role == self.Role.SYSTEM_ADMIN:
            return True
        return super().has_module_perms(app_label)

    def save(self, *args, **kwargs):
        if self.role == self.Role.SYSTEM_ADMIN:
            self.is_staff = True  # type: ignore
            self.is_superuser = True  # type: ignore
        elif self.role == self.Role.BROKER:
            # Brokers are customer reps / operational staff, never superusers.
            # This allows system admins to restrict, deactivate, and manage their permissions.
            self.is_superuser = False  # type: ignore
            if not self.pk and not self.is_staff:
                self.is_staff = True  # type: ignore
        super().save(*args, **kwargs)

    def __str__(self):
        return f"{self.username} ({self.get_role_display()})"


class BrokerStaffManager(UserManager):
    def get_queryset(self):
        return super().get_queryset().filter(role=User.Role.BROKER)


class BrokerStaff(User):
    """Proxy model for dedicated administration and restriction of broker / customer rep accounts."""
    objects = BrokerStaffManager()

    class Meta:
        proxy = True
        verbose_name = "Broker / Customer Rep Account"
        verbose_name_plural = "Broker / Customer Rep Accounts"

    def save(self, *args, **kwargs):
        self.role = User.Role.BROKER
        self.is_superuser = False  # type: ignore
        super().save(*args, **kwargs)


